//! The RK71's physical key layout (from tools/gen_rk71.py).

pub struct Key {
    pub label: &'static str,
    /// Left edge and width in key units; row 0..4.
    pub x: f32,
    pub w: f32,
    pub row: usize,
}

impl Key {
    /// Centre in QMK's LED coordinate space (x 0..224, y 0..64), used by the effect formulas.
    pub fn led_point(&self) -> (f32, f32) {
        ((self.x + self.w / 2.0) / WIDTH_UNITS * 224.0, self.row as f32 / 4.0 * 64.0)
    }
}

pub const WIDTH_UNITS: f32 = 17.0;
pub const ROWS: usize = 5;

const fn k(label: &'static str, x: f32, w: f32, row: usize) -> Key {
    Key { label, x, w, row }
}

